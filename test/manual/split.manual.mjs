import { StudyLoader } from '../../src/dicom/index.js';
import { dirSources, injectWasm } from '../dicom/helpers.js';
import { prepareVolume, analyze, defaultParams } from '../../src/core/index.js';
import { gaussianBlurInt16, solidify, fillEnclosed } from '../../src/core/morph.js';
import { labelComponents } from '../../src/core/components.js';
import { splitBones } from '../../src/core/split.js';
injectWasm();
const loader = new StudyLoader();
const scan = await loader.scan(dirSources(process.argv[2]));
const vol = await loader.buildVolume(scan.recommendedId);
const work = prepareVolume(vol, { maxVoxels: Number(process.argv[3] || 14e6) });
const p = defaultParams(work, analyze(work));
const N = work.hu.length;
const S = gaussianBlurInt16(work.hu, work.dims, p.smoothing);
const mask = new Uint8Array(N); for (let i = 0; i < N; i++) mask[i] = S[i] >= p.threshold ? 1 : 0;
const cc = labelComponents(mask, work.dims, S, p.threshold + 100);
const big = []; for (let c = 1; c <= cc.count; c++) if (cc.size[c] * work.voxel ** 3 > 2000) big.push(c);
const map = new Int32Array(cc.count + 1); big.forEach((c, k) => { map[c] = k + 1; });
const labels = cc.labels; for (let i = 0; i < N; i++) labels[i] = map[labels[i]];
solidify(labels, work.dims, p.closeGapMm / work.voxel, { nParts: big.length }); fillEnclosed(labels, work.dims);
const debug = {};
const r = splitBones(labels, work.dims, S, p.threshold, work.voxel, { debug });
console.log(work.dims, work.voxel, 'thr', p.threshold, r);
const vv = work.voxel ** 3 / 1000;
for (const f of debug.faces.filter((f) => f.lo !== f.hi || f.joint).sort((a, b) => b.total - a.total).slice(0, 28)) console.log(`${f.joint ? 'JOINT' : 'flat '} ${f.lo === f.hi ? '(merged anyway)' : ''} contact ${f.total} vox [${f.n}]  depth ${f.depth} plate ${f.plate} backed ${f.backed}  sizes ${(f.sizeLo * vv).toFixed(1)} / ${(f.sizeHi * vv).toFixed(1)} cm3`);
